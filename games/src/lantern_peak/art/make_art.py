"""Turns the approved ChatGPT proof art (Sprite Drop task aacbf6ea, Kody 2026-11-16: "this works for now as a proof of concept")
into the game's sprites, and writes ../art_data.js (data URIs, so the _mult copy works from a file).
  hero_sheet_77970cdf.png  1536x1024 on a 4x grid -> 384x256 art px -> 6 poses cropped, then 2:1 down to ~42 px tall (the game draws it at 1 world px per art px; the
                           pixel grid is 2 world px, so the hero stands about 56 world px tall with a 44 px body box)
  bg_pinewood_f7841bb6.png 1920x1080 on a 4x grid -> 480x270 art px; see-through sky filled with the brief's colours (cream at the
                           horizon to pale teal #BFE3E8 at the top) and the stray grey bar at the top left removed
python3 make_art.py   (needs Pillow)"""
import os, base64, io
from PIL import Image
D = os.path.dirname(os.path.abspath(__file__))
OUTL = (42, 27, 46, 255)
def down(img, k):
    w, h = img.size; W, H = (w + k - 1) // k, (h + k - 1) // k; src = img.load(); out = Image.new('RGBA', (W, H)); dst = out.load()
    for Y in range(H):
        for X in range(W):
            cnt = {}
            for y in range(Y * k, min(h, Y * k + k)):
                for x in range(X * k, min(w, X * k + k)):
                    c = src[x, y]; c = c if c[3] else (0, 0, 0, 0); cnt[c] = cnt.get(c, 0) + 1
            solid = {c: n for c, n in cnt.items() if c[3]}
            ns = sum(solid.values())
            if cnt.get(OUTL, 0) >= max(2, (k * k) // 3): dst[X, Y] = OUTL
            elif ns >= (k * k) // 2: dst[X, Y] = max(solid.items(), key=lambda t: t[1])[0]
            else: dst[X, Y] = (0, 0, 0, 0)
    return out
def uri(img):
    b = io.BytesIO(); img.save(b, 'PNG', optimize=True); return 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()

sheet = Image.open(D + '/hero_sheet_77970cdf.png').convert('RGBA').resize((384, 256), Image.NEAREST)
px = sheet.load()
cols = [any(px[x, y][3] for y in range(256)) for x in range(384)]
runs, s = [], None
for x, c in enumerate(cols + [False]):
    if c and s is None: s = x
    if not c and s is not None: runs.append((s, x)); s = None
assert len(runs) == 6, runs
names = ['front', 'idle', 'run', 'jump', 'fall', 'land']
FOOT = 174   # the sheet's ground line (art px)
frames = []
for (a, b), n in zip(runs, names):
    ys = [y for y in range(256) if any(px[x, y][3] for x in range(a, b))]
    top = min(ys); bot = FOOT if n not in ('jump', 'fall') else max(ys)
    crop = sheet.crop((a, top, b, max(bot, max(ys)) + 1))
    frames.append((n, down(crop, 2), (a, top)))
# pack into one strip; each frame keeps its own size; the game anchors at bottom-middle
W = sum(f[1].size[0] + 2 for f in frames); H = max(f[1].size[1] for f in frames)
strip = Image.new('RGBA', (W, H)); meta = []; x = 0
for n, im, _ in frames:
    strip.paste(im, (x, H - im.size[1])); meta.append('%s:[%d,%d,%d,%d]' % (n, x, H - im.size[1], im.size[0], im.size[1])); x += im.size[0] + 2
strip.save(D + '/hero_strip.png')
bg = Image.open(D + '/bg_pinewood_f7841bb6.png').convert('RGBA').resize((480, 270), Image.NEAREST)
bp = bg.load()
for y in range(49, 56):       # stray grey bar at the top left (1920 px: x 0-160, y 205-215)
    for x in range(0, 44):
        if bp[x, y][:3] in [(110, 110, 112), (111, 111, 113)] or (abs(bp[x, y][0] - bp[x, y][1]) < 6 and bp[x, y][0] < 140 and bp[x, y][3]): bp[x, y] = (0, 0, 0, 0)
BANDS = [(191, 227, 232), (207, 230, 226), (224, 232, 214), (240, 233, 205), (251, 232, 200)]
sky = Image.new('RGBA', (480, 270)); sp = sky.load()
for y in range(270):
    c = BANDS[min(4, y * 5 // 90)]
    for x in range(480): sp[x, y] = c + (255,)
sky.alpha_composite(bg); sky = sky.convert('RGB')
sky.save(D + '/bg_pinewood_480.png')
js = ('/* generated by art/make_art.py from the approved ChatGPT proof art (Sprite Drop task aacbf6ea). Do not edit by hand. */\n'
      'window.LPPIX={ hero:"%s", heroF:{%s}, bg1:"%s" };\n' % (uri(strip), ','.join(meta), uri(sky)))
open(D + '/../art_data.js', 'w').write(js)
print('strip', strip.size, meta, 'js', len(js))
